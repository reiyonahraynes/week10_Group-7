def make_frame(rows: List[List[Any]], source_file: str = "test.csv") -> pd.DataFrame:

    df = pd.DataFrame(rows, columns=CANONICAL_COLUMNS, dtype=object)
    df.insert(0, "source_record", range(1, len(df) + 1))
    df.insert(0, "source_file", source_file)
    return df


GOOD = ["Japan", "Asia", "2007", "82.603", "127467972", "31656.06806"]


def good(**changes: Any) -> List[Any]:
    """Return a valid row with some fields replaced."""
    row = dict(zip(CANONICAL_COLUMNS, GOOD))
    row.update(changes)
    return [row[c] for c in CANONICAL_COLUMNS]


def default_rules() -> Dict[str, Any]:

    return build_rules({"allowed_continents": ["Africa", "Americas", "Asia", "Europe", "Oceania"],
                        "allowed_years": list(range(1952, 2008, 5))})


class TestRejection(unittest.TestCase):

    def setUp(self) -> None:
        self.rules = default_rules()

    def reasons(self, **changes: Any) -> List[str]:

        return validate_record(dict(zip(CANONICAL_COLUMNS, good(**changes))), self.rules)[0]

    def test_valid_row_passes_and_is_trimmed(self) -> None:
        reasons, typed = validate_record(
            dict(zip(CANONICAL_COLUMNS, good(country="  Japan ", year="2007.0"))), self.rules)
        self.assertEqual(reasons, [])
        self.assertEqual(typed["country"], "Japan")
        self.assertEqual(typed["year"], 2007)
        self.assertIsInstance(typed["pop"], int)

    def test_missing_key_fields_rejected(self) -> None:

        for bad in ["", "   ", None, float("nan"), "None", "nan"]:
            self.assertTrue(self.reasons(country=bad), f"country={bad!r}")
        self.assertTrue(self.reasons(continent=""))
        self.assertTrue(self.reasons(pop=None))
        self.assertTrue(self.reasons(lifeExp=""))

    def test_unparseable_numbers_rejected(self) -> None:

        for field, bad in [("year", "not-a-year"), ("gdpPercap", "not-a-number"),
                           ("pop", "1,000"), ("lifeExp", "1_0"), ("pop", "0x10")]:
            self.assertTrue(self.reasons(**{field: bad}), f"{field}={bad!r}")

    def test_fractional_year_and_population_rejected(self) -> None:

        for bad in ["100.5", 100.5]:
            self.assertTrue(self.reasons(pop=bad))
        for bad in ["2007.5", 1952.5]:
            self.assertTrue(self.reasons(year=bad))
        self.assertEqual(self.reasons(pop="127467972.0"), [])

    def test_non_finite_and_out_of_range_rejected(self) -> None:

        for field, bad in [("lifeExp", "inf"), ("gdpPercap", "-Infinity"), ("lifeExp", "150"),
                           ("lifeExp", "0"), ("pop", "-1"), ("pop", "0"), ("gdpPercap", "0"),
                           ("year", "1953"), ("continent", "Atlantis"), ("lifeExp", "1e999")]:
            self.assertTrue(self.reasons(**{field: bad}), f"{field}={bad!r}")
        self.assertEqual(self.reasons(lifeExp="120"), [])

    def test_json_native_types(self) -> None:

        reasons, typed = validate_record(
            {"country": "Japan", "continent": "Asia", "year": 2007, "lifeExp": 82.603,
             "pop": 127467972, "gdpPercap": 31656.06806}, self.rules)
        self.assertEqual(reasons, [])
        self.assertEqual(typed["pop"], 127467972)
        self.assertTrue(self.reasons(country=None))

    def test_parse_number_kinds(self) -> None:

        self.assertEqual(parse_number("")[1], "missing")
        self.assertEqual(parse_number("abc")[1], "invalid")
        self.assertEqual(parse_number("inf")[1], "non-finite")
        self.assertIsNone(parse_number(" 12.5 ")[1])


class TestQuarantineAndDuplicates(unittest.TestCase):

    def setUp(self) -> None:
        self.run = ValidationRun(default_rules())

    def test_quarantine_keeps_original_values_and_position(self) -> None:
        df = make_frame([good(), good(country="", pop="100.5"), good(country="Peru", continent="Americas")])
        table = self.run.process(df)
        self.assertEqual(len(table), 2)
        q = self.run.quarantine_frame()
        self.assertEqual(list(q.columns), ["source_file", "source_record", "reason"] + CANONICAL_COLUMNS)
        self.assertEqual(q.loc[0, "source_record"], 2)
        self.assertEqual(q.loc[0, "pop"], "100.5")
        self.assertEqual(q.loc[0, "country"], "")

    def test_exact_duplicates_removed_and_logged(self) -> None:
        df = make_frame([good(), good(country="Peru", continent="Americas"), good()])
        table = self.run.process(df)
        self.assertEqual(len(table), 2)
        dup = self.run.duplicate_frame()
        self.assertEqual(len(dup), 1)
        self.assertEqual(dup.loc[0, "source_record"], 3)
        self.assertEqual(dup.loc[0, "duplicate_of_record"], 1)
        self.assertTrue(self.run.reconciles())

    def test_duplicate_with_different_text_format_is_still_exact(self) -> None:

        df = make_frame([good(lifeExp="28.8"), good(lifeExp="28.80")])
        self.assertEqual(len(self.run.process(df)), 1)

    def test_conflicting_keys_stop_processing(self) -> None:

        df = make_frame([good(lifeExp="82.603"), good(lifeExp="83.000")])
        with self.assertRaises(ConflictingKeyError):
            self.run.process(df)

    def test_invalid_rows_are_not_counted_as_duplicates(self) -> None:
        bad = good(pop="-1")
        table = self.run.process(make_frame([good(), bad, bad]))
        self.assertEqual(len(table), 1)
        self.assertEqual(len(self.run.quarantine), 2)
        self.assertEqual(len(self.run.duplicates), 0)

    def test_invalid_row_cannot_cause_conflict(self) -> None:
        table = self.run.process(make_frame([good(), good(lifeExp="150")]))
        self.assertEqual(len(table), 1)

    def test_missing_columns_raise_value_error(self) -> None:
        df = make_frame([good()]).drop(columns=["pop"])
        with self.assertRaises(ValueError):
            self.run.process(df)

    def test_output_types_and_sort_order(self) -> None:
        df = make_frame([good(country="Peru", continent="Americas", year="2002"),
                         good(country="Peru", continent="Americas", year="1952"), good()])
        table = self.run.process(df)
        self.assertEqual(list(table["country"]), ["Japan", "Peru", "Peru"])
        self.assertEqual(list(table["year"]), [2007, 1952, 2002])
        self.assertEqual(str(table["year"].dtype), "int64")
        self.assertEqual(str(table["pop"].dtype), "int64")
        self.assertEqual(str(table["lifeExp"].dtype), "float64")


@unittest.skipUnless(HAS_DATA, "data/ folder not found")
class TestRealFiles(unittest.TestCase):


    @classmethod
    def setUpClass(cls) -> None:
        cls.manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
        cls.specs = {f["file"]: f for f in cls.manifest["files"]}
        cls.rules = build_rules(cls.manifest)

    def prepare(self, df: pd.DataFrame, file: str) -> pd.DataFrame:

        return map_canonical_columns(df, self.specs[file]["source_to_canonical"], CANONICAL_COLUMNS)

    def load_csv(self) -> pd.DataFrame:
        s = self.specs["country_records.csv"]
        df = read_csv_records(DATA_DIR / s["file"], s["encoding"], s["separator"],
                              s["comment_prefix"], s["ignore_columns"])
        return self.prepare(df, s["file"])

    def load_xlsx(self) -> pd.DataFrame:
        s = self.specs["country_records.xlsx"]
        return self.prepare(read_excel_records(DATA_DIR / s["file"], s["sheet_name"], s["engine"]), s["file"])

    def load_json(self) -> pd.DataFrame:
        return self.prepare(read_json_records(DATA_DIR / "country_records.json"), "country_records.json")

    def load_parquet(self) -> pd.DataFrame:
        return self.prepare(read_parquet_records(DATA_DIR / "country_records.parquet"),
                            "country_records.parquet")

    def loaders(self) -> List[Any]:

        found = [self.load_csv, self.load_xlsx, self.load_json]
        return found + [self.load_parquet] if HAS_PARQUET else found

    def check_normal(self, df: pd.DataFrame) -> pd.DataFrame:

        run = ValidationRun(self.rules)
        table = run.process(df)
        self.assertEqual(run.counts, {"raw": 1712, "rejected": 6, "duplicates": 2, "canonical": 1704})
        self.assertTrue(run.reconciles())
        self.assertEqual(len(run.quarantine_frame()), 6)
        self.assertEqual(len(run.duplicate_frame()), 2)
        self.assertEqual(table[["country", "year"]].duplicated().sum(), 0)
        return table

    def test_csv(self) -> None:
        df = self.load_csv()
        run = ValidationRun(self.rules)
        run.process(df)
        self.assertEqual(run.counts["canonical"], 1704)
        self.assertEqual(sorted(run.quarantine_frame()["source_record"]), [77, 232, 377, 647, 973, 1176])
        self.check_normal(df)

    def test_xlsx(self) -> None:
        self.check_normal(self.load_xlsx())

    def test_json(self) -> None:
        self.check_normal(self.load_json())

    @unittest.skipUnless(HAS_PARQUET, "pyarrow not installed")
    def test_parquet(self) -> None:
        self.check_normal(self.load_parquet())

    def test_formats_agree_and_controls_hold(self) -> None:
        tables = [self.check_normal(load()) for load in self.loaders()]
        for other in tables[1:]:
            pd.testing.assert_frame_equal(tables[0], other, check_exact=True)
        controls = self.manifest["controls"]
        csv = tables[0]
        self.assertEqual(csv["country"].nunique(), controls["countries"])
        self.assertEqual(int((csv["country"] == "Philippines").sum()), controls["philippines_rows"])
        asia = csv.loc[(csv["continent"] == "Asia") & (csv["year"] == 2007)]
        self.assertEqual(len(asia), controls["asia_2007_rows"])
        self.assertEqual(int(asia["pop"].sum()), controls["asia_2007_population"])

    def test_reordered_records_give_same_table(self) -> None:

        df = self.load_csv()
        shuffled = df.sample(frac=1, random_state=7).reset_index(drop=True)
        a = ValidationRun(self.rules).process(df)
        b = ValidationRun(self.rules).process(shuffled)
        pd.testing.assert_frame_equal(a, b, check_exact=True)

    def test_conflicting_key_csv_fails(self) -> None:
        df = read_csv_records(DATA_DIR / "conflicting_key.csv", "utf-8", ",", None)
        with self.assertRaises(ConflictingKeyError):
            ValidationRun(self.rules).process(df)

    def test_missing_column_csv_fails(self) -> None:
        df = read_csv_records(DATA_DIR / "missing_column.csv", "utf-8", ",", None)
        with self.assertRaises(ValueError):
            ValidationRun(self.rules).process(df)


